#!/usr/bin/env node
/**
 * Collects what the hosted jury runner needs from your local near-cli keychain into a gitignored file,
 * so you can paste it into Railway's "Raw Editor" for variables. Secrets are NOT printed.
 *   node scripts/export-runner-env.mjs [--out .env.railway]
 * Reads: ~/.near-credentials/<network>/v*.<contract>.json (verifier FCAKs) and
 *        ~/.near-credentials/juri/<network>/keeper-fcak.json (keeper FCAK).
 * Each of these keys can only call its few contract methods (03 §6); the owner key is never included.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(import.meta.url), "../..");
const argv = process.argv.slice(2);
const out = resolve(ROOT, argv.includes("--out") ? argv[argv.indexOf("--out") + 1] : ".env.railway");
if (!/[\\/]\.env\.[^\\/]+$/.test(out)) {
  console.error("--out must be a .env.<name> file (gitignored)");
  process.exit(2);
}

const env = existsSync(join(ROOT, ".env"))
  ? Object.fromEntries(
      readFileSync(join(ROOT, ".env"), "utf8")
        .split(/\r?\n/)
        .filter((l) => /^[A-Z_][A-Z0-9_]*=/.test(l))
        .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).trim()]),
    )
  : {};
const network = process.env.NEAR_NETWORK || env.NEAR_NETWORK || "testnet";
const root = process.env.NEAR_ROOT_ACCOUNT || env.NEAR_ROOT_ACCOUNT || "juri-assay-jdir.testnet";
const contract = process.env.JURI_CONTRACT_ID || env.JURI_CONTRACT_ID || `juri.${root}`;
const creds = process.env.NEAR_CREDENTIALS_DIR || join(homedir(), ".near-credentials");

const verifiers = {};
const dir = join(creds, network);
if (existsSync(dir))
  for (const f of readdirSync(dir).filter((f) => f.endsWith(`.${contract}.json`) && /^v\d+\./.test(f))) {
    const k = JSON.parse(readFileSync(join(dir, f), "utf8"));
    verifiers[f.slice(0, -5)] = k.private_key;
  }
const keeperFile = join(creds, "juri", network, "keeper-fcak.json");
const keeper = existsSync(keeperFile) ? JSON.parse(readFileSync(keeperFile, "utf8")) : null;

const pick = (k) => (process.env[k] || env[k] ? `${k}=${process.env[k] || env[k]}` : null);
const lines = [
  "# generated by scripts/export-runner-env.mjs — paste into Railway → Variables → Raw Editor, then delete this file",
  "MODE=live",
  `NEAR_NETWORK=${network}`,
  `NEAR_ROOT_ACCOUNT=${root}`,
  `JURI_CONTRACT_ID=${contract}`,
  pick("NEAR_RPC_URL") ?? "NEAR_RPC_URL=https://test.rpc.fastnear.com",
  `VERIFIER_KEYS_JSON=${JSON.stringify(verifiers)}`,
  keeper ? `KEEPER_ACCOUNT_ID=${keeper.account_id}` : "# KEEPER_ACCOUNT_ID= (no keeper-fcak.json found)",
  keeper ? `KEEPER_KEY=${keeper.private_key}` : "# KEEPER_KEY=",
  "AUTO_START=true",
  "TRUST_PROXY=1",
  pick("NEARAI_API_KEY") ?? "# NEARAI_API_KEY=",
  pick("NEARAI_BASE_URL"),
  pick("VERIFIER_MODELS_JSON"),
  pick("FALLBACK_LLM_BASE_URL"),
  pick("FALLBACK_LLM_API_KEY"),
  pick("MARKET_API_KEY"),
  pick("DELIVERABLE_URI_ALLOWLIST"),
  "# set PUBLIC_API_URL to the Railway public URL, e.g. https://assay-api.up.railway.app",
  "PUBLIC_API_URL=",
].filter(Boolean);

writeFileSync(out, `${lines.join("\n")}\n`, { mode: 0o600 });
console.log(`wrote ${out}`);
console.log(`  verifiers: ${Object.keys(verifiers).join(", ") || "none found in " + dir}`);
console.log(`  keeper: ${keeper ? keeper.account_id : "not found (" + keeperFile + ")"}`);
console.log(`  NEARAI_API_KEY: ${pick("NEARAI_API_KEY") ? "included" : "missing"} · MARKET_API_KEY: ${pick("MARKET_API_KEY") ? "included" : "missing"}`);
console.log("No secret was printed. Paste the file into Railway, then delete it.");
